-- 0136: разглаживание номиналов звёзд в кейсе «Ежедневный» (case_id = 1, shop_case_rewards id = 49).
--
-- ПРИЧИНА. Звёзды занимают 77% выпадений кейса, но веса discrete_amounts
-- 30/24/14/7/2 сажали 39% из них на минимум: 2⭐ выпадали в 30% всех открытий,
-- а 2⭐ или 4⭐ — в 54%. Эффективных номиналов 3.9 из 5.
--
-- ЧТО ДЕЛАЕМ. Добавляем промежуточные номиналы 3/5/8⭐ (они попадают в уже
-- заданный диапазон min_amount=2 / max_amount=20, поэтому getEffectiveDiscreteAmounts
-- их не отфильтрует) и выравниваем веса. chance_percent строки НЕ трогаем —
-- доля звёзд в кейсе остаётся 77%.
--
-- ЭКОНОМИКА. Среднее по звёздам 4.55⭐ → 4.59⭐, то есть +0.002⚽ к ценности кейса
-- (0.758⚽ → 0.760⚽) и +0.0004⚽ к спину колеса, где кейс сидит сектором на 25%.
-- RTP и эмиссия не двигаются: звезда стоит 0.05⚽ по курсу обмена 20⭐ = 1⚽.
--   топ-исход кейса        30.0% → 18.5% открытий
--   эффективных номиналов   3.9  → 6.7
--
-- ДАННЫЕ. Правится только meta_json одной строки; проценты остальных наград
-- (мячи 8%, жетон 6.8%, джокер 4%, двойной шанс 4%, слот 0.2%) не затрагиваются.

UPDATE shop_case_rewards
SET meta_json = '{"discrete_amounts": [{"amount": 2, "weight": 24}, {"amount": 3, "weight": 20}, {"amount": 4, "weight": 18}, {"amount": 5, "weight": 13}, {"amount": 6, "weight": 10}, {"amount": 8, "weight": 8}, {"amount": 10, "weight": 5}, {"amount": 20, "weight": 2}]}'
WHERE id = 49 AND case_id = 1 AND reward_type = 'stars';
